
"""
File 59: modules/video_generation_manager.py

Video Generation Manager

Features:
- Text-to-video and image-to-video job preparation.
- Character and scene metadata.
- Motion and camera movement prompts.
- Duration, FPS, aspect ratio and resolution settings.
- Job status tracking.
- Register generated video files.
- Search, duplicate, delete and export jobs.
- Optional Streamlit interface.

This module does not run an AI video-generation model.
It manages jobs and registers videos generated by another engine.
"""

from __future__ import annotations

import json
import shutil
import uuid

from datetime import datetime
from pathlib import Path
from typing import Any


ROOT_DIR = Path(__file__).resolve().parent.parent

DATA_DIR = ROOT_DIR / "data"
OUTPUT_DIR = ROOT_DIR / "outputs" / "video_generation"
GENERATED_DIR = OUTPUT_DIR / "generated"

DATA_FILE = DATA_DIR / "video_generation_jobs.json"

GENERATION_MODES = [
    "Text to Video",
    "Image to Video",
]

VIDEO_STYLES = [
    "Photorealistic",
    "Hollywood Cinematic",
    "3D CGI",
    "Fantasy",
    "Sci-Fi",
    "Anime",
    "Documentary",
    "Custom",
]

ASPECT_RATIOS = [
    "16:9",
    "9:16",
    "1:1",
    "4:3",
    "21:9",
]

RESOLUTIONS = [
    "480p",
    "720p",
    "1080p",
    "Custom",
]

FPS_OPTIONS = [12, 15, 24, 25, 30, 50, 60]

MOTION_INTENSITIES = [
    "Very Low",
    "Low",
    "Medium",
    "High",
    "Very High",
]

CAMERA_MOVEMENTS = [
    "Static",
    "Slow Push In",
    "Slow Pull Out",
    "Pan Left",
    "Pan Right",
    "Tilt Up",
    "Tilt Down",
    "Tracking Shot",
    "Orbit",
    "Handheld",
    "Dolly Zoom",
    "Crane Shot",
]

JOB_STATUSES = [
    "Draft",
    "Ready",
    "Generating",
    "Completed",
    "Failed",
    "Cancelled",
]

SUPPORTED_VIDEO_EXTENSIONS = {
    ".mp4",
    ".mov",
    ".mkv",
    ".webm",
    ".avi",
}


class VideoGenerationError(Exception):
    """Base exception for video-generation workflow errors."""


def _ensure_directories() -> None:
    for directory in (
        DATA_DIR,
        OUTPUT_DIR,
        GENERATED_DIR,
    ):
        directory.mkdir(parents=True, exist_ok=True)


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _clean(value: Any) -> str:
    return str(value or "").strip()


def _read_jobs() -> list[dict[str, Any]]:
    _ensure_directories()

    if not DATA_FILE.exists():
        return []

    try:
        with DATA_FILE.open("r", encoding="utf-8") as file:
            data = json.load(file)

    except (OSError, json.JSONDecodeError) as exc:
        raise VideoGenerationError(
            f"Could not read video job database: {exc}"
        ) from exc

    if not isinstance(data, list):
        raise VideoGenerationError(
            "Video job database must contain a JSON list."
        )

    return [
        item for item in data
        if isinstance(item, dict)
    ]


def _write_jobs(jobs: list[dict[str, Any]]) -> None:
    _ensure_directories()

    temporary_file = DATA_FILE.with_suffix(".tmp")

    try:
        with temporary_file.open("w", encoding="utf-8") as file:
            json.dump(
                jobs,
                file,
                indent=4,
                ensure_ascii=False,
            )

        temporary_file.replace(DATA_FILE)

    except OSError as exc:
        raise VideoGenerationError(
            f"Could not save video jobs: {exc}"
        ) from exc


def build_video_prompt(
    character_name: str,
    scene_description: str,
    motion_prompt: str,
    visual_style: str,
    camera_movement: str,
    motion_intensity: str,
    lighting: str = "",
    extra_instructions: str = "",
) -> str:
    """Build a structured video-generation prompt."""

    parts = [
        f"Character: {character_name}",
        f"Scene: {scene_description}",
        f"Motion: {motion_prompt}",
        f"Visual style: {visual_style}",
        f"Camera movement: {camera_movement}",
        f"Motion intensity: {motion_intensity}",
        f"Lighting: {lighting}",
        extra_instructions,
        (
            "Maintain consistent character appearance, "
            "facial features, clothing and proportions "
            "throughout the entire video."
        ),
        (
            "Use smooth natural movement, stable anatomy "
            "and consistent scene continuity."
        ),
    ]

    return ", ".join(
        part.strip()
        for part in parts
        if part and part.strip()
    )


def create_job(
    character_name: str,
    scene_description: str,
    generation_mode: str = "Text to Video",
    motion_prompt: str = "",
    visual_style: str = "Photorealistic",
    negative_prompt: str = "",
    reference_image_path: str = "",
    duration_seconds: float = 5,
    aspect_ratio: str = "16:9",
    resolution: str = "720p",
    custom_resolution: str = "",
    fps: int = 24,
    motion_intensity: str = "Medium",
    camera_movement: str = "Static",
    lighting: str = "Cinematic lighting",
    extra_instructions: str = "",
    notes: str = "",
    status: str = "Draft",
) -> dict[str, Any]:
    """Create and save a video-generation job."""

    character_name = _clean(character_name)
    scene_description = _clean(scene_description)

    if not character_name:
        raise ValueError("Character name is required.")

    if not scene_description:
        raise ValueError("Scene description is required.")

    if generation_mode not in GENERATION_MODES:
        raise ValueError("Invalid generation mode.")

    if visual_style not in VIDEO_STYLES:
        raise ValueError("Invalid visual style.")

    if aspect_ratio not in ASPECT_RATIOS:
        raise ValueError("Invalid aspect ratio.")

    if resolution not in RESOLUTIONS:
        raise ValueError("Invalid resolution.")

    if motion_intensity not in MOTION_INTENSITIES:
        raise ValueError("Invalid motion intensity.")

    if camera_movement not in CAMERA_MOVEMENTS:
        raise ValueError("Invalid camera movement.")

    if status not in JOB_STATUSES:
        raise ValueError("Invalid job status.")

    duration_seconds = float(duration_seconds)

    if not 1 <= duration_seconds <= 600:
        raise ValueError(
            "Duration must be between 1 and 600 seconds."
        )

    fps = int(fps)

    if fps not in FPS_OPTIONS:
        raise ValueError(
            f"FPS must be one of: {FPS_OPTIONS}"
        )

    final_resolution = (
        _clean(custom_resolution)
        if resolution == "Custom"
        else resolution
    )

    if resolution == "Custom" and not final_resolution:
        raise ValueError("Enter a custom resolution.")

    reference_image_path = _clean(reference_image_path)

    if generation_mode == "Image to Video":
        if not reference_image_path:
            raise ValueError(
                "Image-to-video requires a reference image path."
            )

        reference = Path(reference_image_path).expanduser()

        if not reference.is_file():
            raise FileNotFoundError(
                f"Reference image not found: {reference}"
            )

        reference_image_path = str(reference.resolve())

    prompt = build_video_prompt(
        character_name=character_name,
        scene_description=scene_description,
        motion_prompt=_clean(motion_prompt),
        visual_style=visual_style,
        camera_movement=camera_movement,
        motion_intensity=motion_intensity,
        lighting=_clean(lighting),
        extra_instructions=_clean(extra_instructions),
    )

    job = {
        "id": uuid.uuid4().hex[:12],
        "character_name": character_name,
        "generation_mode": generation_mode,
        "scene_description": scene_description,
        "motion_prompt": _clean(motion_prompt),
        "positive_prompt": prompt,
        "negative_prompt": _clean(negative_prompt),
        "visual_style": visual_style,
        "reference_image_path": reference_image_path or None,
        "duration_seconds": duration_seconds,
        "aspect_ratio": aspect_ratio,
        "resolution": final_resolution,
        "fps": fps,
        "motion_intensity": motion_intensity,
        "camera_movement": camera_movement,
        "lighting": _clean(lighting),
        "extra_instructions": _clean(extra_instructions),
        "notes": _clean(notes),
        "status": status,
        "generated_video": None,
        "error_message": "",
        "created_at": _now(),
        "updated_at": _now(),
    }

    jobs = _read_jobs()
    jobs.append(job)
    _write_jobs(jobs)

    return job


def list_jobs(
    character_name: str | None = None,
    status: str = "All",
    generation_mode: str = "All",
) -> list[dict[str, Any]]:
    """List video jobs with optional filters."""

    jobs = _read_jobs()

    if character_name:
        target = character_name.casefold().strip()

        jobs = [
            job for job in jobs
            if job.get("character_name", "").casefold() == target
        ]

    if status != "All":
        jobs = [
            job for job in jobs
            if job.get("status") == status
        ]

    if generation_mode != "All":
        jobs = [
            job for job in jobs
            if job.get("generation_mode") == generation_mode
        ]

    return sorted(
        jobs,
        key=lambda job: job.get("created_at", ""),
        reverse=True,
    )


def get_job(job_id: str) -> dict[str, Any] | None:
    """Return a job by ID."""

    return next(
        (
            job for job in _read_jobs()
            if job.get("id") == job_id
        ),
        None,
    )


def update_job_status(
    job_id: str,
    status: str,
    error_message: str = "",
) -> dict[str, Any]:
    """Update job status and optional error information."""

    if status not in JOB_STATUSES:
        raise ValueError("Invalid job status.")

    jobs = _read_jobs()

    for job in jobs:
        if job.get("id") == job_id:
            job["status"] = status
            job["error_message"] = _clean(error_message)
            job["updated_at"] = _now()

            _write_jobs(jobs)
            return job

    raise VideoGenerationError("Video job not found.")


def register_generated_video(
    job_id: str,
    video_path: str,
    copy_video: bool = True,
) -> dict[str, Any]:
    """
    Register a video produced by another generation engine.

    This function does not generate or encode video.
    """

    source = Path(video_path).expanduser()

    if not source.is_file():
        raise FileNotFoundError(
            f"Generated video not found: {source}"
        )

    extension = source.suffix.lower()

    if extension not in SUPPORTED_VIDEO_EXTENSIONS:
        raise ValueError(
            "Unsupported video format. Supported formats: "
            + ", ".join(sorted(SUPPORTED_VIDEO_EXTENSIONS))
        )

    jobs = _read_jobs()

    target = next(
        (job for job in jobs if job.get("id") == job_id),
        None,
    )

    if target is None:
        raise VideoGenerationError("Video job not found.")

    _ensure_directories()

    final_path = source.resolve()

    if copy_video:
        destination = (
            GENERATED_DIR
            / f"{job_id}_{uuid.uuid4().hex[:6]}{extension}"
        )

        try:
            shutil.copy2(source, destination)
        except OSError as exc:
            raise VideoGenerationError(
                f"Could not copy video: {exc}"
            ) from exc

        final_path = destination

    target["generated_video"] = str(final_path)
    target["status"] = "Completed"
    target["error_message"] = ""
    target["updated_at"] = _now()

    _write_jobs(jobs)

    return target


def delete_job(
    job_id: str,
    delete_generated_video: bool = False,
) -> bool:
    """Delete job metadata and optionally its managed video."""

    jobs = _read_jobs()

    target = next(
        (job for job in jobs if job.get("id") == job_id),
        None,
    )

    if target is None:
        return False

    remaining = [
        job for job in jobs
        if job.get("id") != job_id
    ]

    _write_jobs(remaining)

    if delete_generated_video:
        video_value = target.get("generated_video")

        if video_value:
            try:
                video_path = Path(video_value).resolve()
                managed_dir = GENERATED_DIR.resolve()

                if (
                    video_path.is_relative_to(managed_dir)
                    and video_path.is_file()
                ):
                    video_path.unlink()

            except (OSError, ValueError):
                pass

    return True


def duplicate_job(job_id: str) -> dict[str, Any]:
    """Duplicate a video job as a new draft."""

    original = get_job(job_id)

    if original is None:
        raise VideoGenerationError("Video job not found.")

    duplicate = dict(original)

    duplicate["id"] = uuid.uuid4().hex[:12]
    duplicate["status"] = "Draft"
    duplicate["generated_video"] = None
    duplicate["error_message"] = ""
    duplicate["created_at"] = _now()
    duplicate["updated_at"] = _now()
    duplicate["notes"] = (
        f"Duplicated from {job_id}. "
        + original.get("notes", "")
    ).strip()

    jobs = _read_jobs()
    jobs.append(duplicate)
    _write_jobs(jobs)

    return duplicate


def search_jobs(query: str) -> list[dict[str, Any]]:
    """Search character, scene, prompt and notes."""

    query = _clean(query).casefold()
    jobs = _read_jobs()

    if not query:
        return jobs

    results = []

    for job in jobs:
        searchable = " ".join([
            job.get("character_name", ""),
            job.get("scene_description", ""),
            job.get("motion_prompt", ""),
            job.get("positive_prompt", ""),
            job.get("notes", ""),
        ]).casefold()

        if query in searchable:
            results.append(job)

    return results


def get_statistics() -> dict[str, int]:
    """Return job counts."""

    jobs = _read_jobs()

    return {
        "total": len(jobs),
        "draft": sum(
            job.get("status") == "Draft" for job in jobs
        ),
        "ready": sum(
            job.get("status") == "Ready" for job in jobs
        ),
        "generating": sum(
            job.get("status") == "Generating" for job in jobs
        ),
        "completed": sum(
            job.get("status") == "Completed" for job in jobs
        ),
        "failed": sum(
            job.get("status") == "Failed" for job in jobs
        ),
        "with_video": sum(
            bool(job.get("generated_video")) for job in jobs
        ),
    }


def export_jobs() -> Path:
    """Export all video jobs to JSON."""

    _ensure_directories()

    destination = OUTPUT_DIR / (
        "video_jobs_"
        + datetime.now().strftime("%Y%m%d_%H%M%S")
        + ".json"
    )

    payload = {
        "exported_at": _now(),
        "jobs": _read_jobs(),
    }

    with destination.open("w", encoding="utf-8") as file:
        json.dump(
            payload,
            file,
            indent=4,
            ensure_ascii=False,
        )

    return destination


def render() -> None:
    """Render the Streamlit video manager page."""

    try:
        import streamlit as st
    except ImportError:
        raise RuntimeError(
            "Streamlit is required for this page. "
            "Install it using: pip install streamlit"
        )

    st.title("Video Generation Manager")
    st.caption(
        "Prepare and manage text-to-video and image-to-video jobs."
    )

    try:
        stats = get_statistics()

        columns = st.columns(4)
        columns[0].metric("Total Jobs", stats["total"])
        columns[1].metric("Ready", stats["ready"])
        columns[2].metric("Completed", stats["completed"])
        columns[3].metric("Generated Videos", stats["with_video"])

        tab_create, tab_manage, tab_export = st.tabs([
            "Create Video Job",
            "Manage Video Jobs",
            "Export",
        ])

        with tab_create:
            st.subheader("New video-generation job")

            character_name = st.text_input(
                "Character name",
                placeholder="Example: Eira",
            )

            generation_mode = st.selectbox(
                "Generation mode",
                GENERATION_MODES,
            )

            scene_description = st.text_area(
                "Scene description",
                height=110,
                placeholder=(
                    "Describe the scene, background, "
                    "character position and action."
                ),
            )

            motion_prompt = st.text_area(
                "Motion prompt",
                placeholder=(
                    "Example: Character slowly turns head, "
                    "hair moves naturally in the wind."
                ),
            )

            reference_image_path = ""

            if generation_mode == "Image to Video":
                uploaded_reference = st.file_uploader(
                    "Upload starting reference image",
                    type=["png", "jpg", "jpeg", "webp"],
                    key="video_reference_upload",
                )

                if uploaded_reference is not None:
                    st.image(
                        uploaded_reference,
                        caption="Starting reference image",
                        width=280,
                    )

            negative_prompt = st.text_area(
                "Negative prompt",
                value=(
                    "flicker, jitter, distorted face, "
                    "extra limbs, unstable anatomy, "
                    "inconsistent clothing, sudden scene changes, "
                    "blurry frames, unwanted text"
                ),
            )

            col1, col2 = st.columns(2)

            with col1:
                visual_style = st.selectbox(
                    "Visual style",
                    VIDEO_STYLES,
                )

                motion_intensity = st.selectbox(
                    "Motion intensity",
                    MOTION_INTENSITIES,
                    index=2,
                )

                camera_movement = st.selectbox(
                    "Camera movement",
                    CAMERA_MOVEMENTS,
                )

                lighting = st.selectbox(
                    "Lighting",
                    [
                        "Cinematic lighting",
                        "Natural daylight",
                        "Golden hour",
                        "Dark dramatic lighting",
                        "Neon lighting",
                        "Soft studio lighting",
                    ],
                )

            with col2:
                duration_seconds = st.number_input(
                    "Duration (seconds)",
                    min_value=1.0,
                    max_value=600.0,
                    value=5.0,
                    step=1.0,
                )

                aspect_ratio = st.selectbox(
                    "Aspect ratio",
                    ASPECT_RATIOS,
                )

                resolution = st.selectbox(
                    "Resolution",
                    RESOLUTIONS,
                    index=RESOLUTIONS.index("720p"),
                )

                fps = st.selectbox(
                    "Frames per second",
                    FPS_OPTIONS,
                    index=FPS_OPTIONS.index(24),
                )

            custom_resolution = ""

            if resolution == "Custom":
                custom_resolution = st.text_input(
                    "Custom resolution",
                    placeholder="Example: 1280x720",
                )

            extra_instructions = st.text_area(
                "Extra instructions",
                placeholder=(
                    "Character consistency, environment details, "
                    "scene continuity, visual effects, etc."
                ),
            )

            notes = st.text_area("Job notes")

            if st.button(
                "Create Video Job",
                type="primary",
                use_container_width=True,
            ):
                try:
                    if (
                        generation_mode == "Image to Video"
                        and uploaded_reference is not None
                    ):
                        _ensure_directories()

                        suffix = (
                            Path(uploaded_reference.name).suffix
                            or ".png"
                        )

                        reference_destination = (
                            OUTPUT_DIR
                            / f"reference_{uuid.uuid4().hex}{suffix}"
                        )

                        reference_destination.write_bytes(
                            uploaded_reference.getvalue()
                        )

                        reference_image_path = str(
                            reference_destination
                        )

                    job = create_job(
                        character_name=character_name,
                        scene_description=scene_description,
                        generation_mode=generation_mode,
                        motion_prompt=motion_prompt,
                        visual_style=visual_style,
                        negative_prompt=negative_prompt,
                        reference_image_path=reference_image_path,
                        duration_seconds=duration_seconds,
                        aspect_ratio=aspect_ratio,
                        resolution=resolution,
                        custom_resolution=custom_resolution,
                        fps=fps,
                        motion_intensity=motion_intensity,
                        camera_movement=camera_movement,
                        lighting=lighting,
                        extra_instructions=extra_instructions,
                        notes=notes,
                        status="Ready",
                    )

                    st.success(
                        f"Video job created: {job['id']}"
                    )

                    with st.expander("View generated prompt"):
                        st.code(job["positive_prompt"])

                except Exception as exc:
                    st.error(f"Could not create video job: {exc}")

        with tab_manage:
            st.subheader("Manage video jobs")

            query = st.text_input(
                "Search character, scene or prompt",
                key="video_job_search",
            )

            status_filter = st.selectbox(
                "Filter by status",
                ["All"] + JOB_STATUSES,
                key="video_status_filter",
            )

            mode_filter = st.selectbox(
                "Filter by generation mode",
                ["All"] + GENERATION_MODES,
                key="video_mode_filter",
            )

            jobs = (
                search_jobs(query)
                if query.strip()
                else list_jobs()
            )

            if status_filter != "All":
                jobs = [
                    job for job in jobs
                    if job.get("status") == status_filter
                ]

            if mode_filter != "All":
                jobs = [
                    job for job in jobs
                    if job.get("generation_mode") == mode_filter
                ]

            if not jobs:
                st.info("No video jobs found.")

            for job in jobs:
                job_id = job["id"]

                with st.container(border=True):
                    st.markdown(
                        f"**{job.get('character_name', 'Unknown')}**"
                    )

                    st.caption(
                        f"{job.get('generation_mode')} · "
                        f"{job.get('status')} · "
                        f"{job_id}"
                    )

                    st.write(job.get("scene_description", ""))

                    with st.expander("View prompt and settings"):
                        st.markdown("**Positive prompt**")
                        st.code(job.get("positive_prompt", ""))

                        st.markdown("**Negative prompt**")
                        st.code(job.get("negative_prompt", ""))

                        st.json({
                            "duration": job.get("duration_seconds"),
                            "aspect_ratio": job.get("aspect_ratio"),
                            "resolution": job.get("resolution"),
                            "fps": job.get("fps"),
                            "motion_intensity": job.get("motion_intensity"),
                            "camera_movement": job.get("camera_movement"),
                        })

                    generated_video = job.get("generated_video")

                    if generated_video:
                        video_path = Path(generated_video)

                        if video_path.is_file():
                            try:
                                st.video(str(video_path))
                            except Exception as exc:
                                st.warning(
                                    f"Video preview unavailable: {exc}"
                                )
                        else:
                            st.warning(
                                "The registered video file is missing."
                            )

                    left, right = st.columns(2)

                    with left:
                        new_status = st.selectbox(
                            "Job status",
                            JOB_STATUSES,
                            index=(
                                JOB_STATUSES.index(job["status"])
                                if job.get("status") in JOB_STATUSES
                                else 0
                            ),
                            key=f"video_status_{job_id}",
                        )

                        error_message = st.text_input(
                            "Error message (optional)",
                            value=job.get("error_message", ""),
                            key=f"video_error_{job_id}",
                        )

                        if st.button(
                            "Update Status",
                            key=f"video_update_{job_id}",
                        ):
                            update_job_status(
                                job_id,
                                new_status,
                                error_message,
                            )
                            st.success("Status updated.")
                            st.rerun()

                    with right:
                        uploaded_video = st.file_uploader(
                            "Register generated video",
                            type=[
                                "mp4",
                                "mov",
                                "mkv",
                                "webm",
                                "avi",
                            ],
                            key=f"video_upload_{job_id}",
                        )

                        if st.button(
                            "Save Generated Video",
                            key=f"video_register_{job_id}",
                        ):
                            if uploaded_video is None:
                                st.warning("Upload a video first.")
                            else:
                                _ensure_directories()

                                suffix = (
                                    Path(uploaded_video.name).suffix
                                    or ".mp4"
                                )

                                temporary = (
                                    GENERATED_DIR
                                    / f"upload_{uuid.uuid4().hex}{suffix}"
                                )

                                try:
                                    temporary.write_bytes(
                                        uploaded_video.getvalue()
                                    )

                                    register_generated_video(
                                        job_id,
                                        str(temporary),
                                        copy_video=True,
                                    )

                                    st.success(
                                        "Generated video registered."
                                    )
                                    st.rerun()

                                except Exception as exc:
                                    st.error(str(exc))

                                finally:
                                    temporary.unlink(missing_ok=True)

                    action1, action2 = st.columns(2)

                    with action1:
                        if st.button(
                            "Duplicate Job",
                            key=f"video_duplicate_{job_id}",
                        ):
                            duplicate = duplicate_job(job_id)
                            st.success(
                                f"Duplicate created: {duplicate['id']}"
                            )
                            st.rerun()

                    with action2:
                        if st.button(
                            "Delete Job",
                            key=f"video_delete_{job_id}",
                        ):
                            delete_job(
                                job_id,
                                delete_generated_video=True,
                            )
                            st.success("Job deleted.")
                            st.rerun()

        with tab_export:
            st.subheader("Export video jobs")

            if st.button("Create JSON Export"):
                destination = export_jobs()

                st.success("Export created.")

                st.download_button(
                    "Download video jobs",
                    data=destination.read_bytes(),
                    file_name=destination.name,
                    mime="application/json",
                )

            st.info(
                "Actual AI video generation requires a compatible "
                "local generation engine. This module does not "
                "automatically download models or call cloud APIs."
            )

    except Exception as exc:
        st.error(
            "Video Generation Manager encountered an error. "
            "Other application modules should remain available."
        )
        st.exception(exc)


def run_tests() -> None:
    """Run built-in tests using temporary folders."""

    import tempfile

    global DATA_DIR
    global OUTPUT_DIR
    global GENERATED_DIR
    global DATA_FILE

    old_values = (
        DATA_DIR,
        OUTPUT_DIR,
        GENERATED_DIR,
        DATA_FILE,
    )

    try:
        with tempfile.TemporaryDirectory() as temporary:
            base = Path(temporary)

            DATA_DIR = base / "data"
            OUTPUT_DIR = base / "outputs"
            GENERATED_DIR = OUTPUT_DIR / "generated"
            DATA_FILE = DATA_DIR / "video_generation_jobs.json"

            _ensure_directories()

            job = create_job(
                character_name="Test Character",
                scene_description="A character walking in a forest",
                generation_mode="Text to Video",
                motion_prompt="Slow natural walking",
                visual_style="Photorealistic",
                negative_prompt="flickering",
                duration_seconds=5,
                aspect_ratio="16:9",
                resolution="720p",
                fps=24,
                motion_intensity="Medium",
                camera_movement="Tracking Shot",
                status="Ready",
            )

            assert job["character_name"] == "Test Character"
            assert job["status"] == "Ready"
            assert "forest" in job["positive_prompt"]

            assert len(list_jobs()) == 1
            assert get_job(job["id"]) is not None

            updated = update_job_status(
                job["id"],
                "Generating",
            )
            assert updated["status"] == "Generating"

            duplicate = duplicate_job(job["id"])
            assert duplicate["id"] != job["id"]
            assert duplicate["status"] == "Draft"

            sample_video = base / "sample.mp4"
            sample_video.write_bytes(b"test-video-data")

            registered = register_generated_video(
                job["id"],
                str(sample_video),
                copy_video=True,
            )

            assert registered["status"] == "Completed"
            assert Path(
                registered["generated_video"]
            ).is_file()

            assert search_jobs("forest")

            stats = get_statistics()
            assert stats["total"] == 2
            assert stats["completed"] == 1

            exported = export_jobs()
            assert exported.is_file()

            assert delete_job(
                job["id"],
                delete_generated_video=True,
            )

            assert get_job(job["id"]) is None

            # Validate image-to-video input checks.
            try:
                create_job(
                    character_name="Test",
                    scene_description="Test scene",
                    generation_mode="Image to Video",
                    reference_image_path="missing_reference.png",
                )
            except FileNotFoundError:
                pass
            else:
                raise AssertionError(
                    "Missing image reference should be rejected."
                )

            print("All Video Generation Manager tests passed.")

    finally:
        (
            DATA_DIR,
            OUTPUT_DIR,
            GENERATED_DIR,
            DATA_FILE,
        ) = old_values


